let changed = 0;
for (const d of data) {
  let html = readFileSync(d.file, 'utf8');
  if (html.includes(MARK)) { console.log(`SKIP (déjà enrichi): ${d.file}`); continue; }

  // 1) Title (premier <title>, celui injecté par seo-enrich)
  html = html.replace(/<title>[\s\S]*?<\/title>/, `<title>${d.title}</title>`);

  // 2) Meta description
  html = html.replace(/<meta name="description" content="[^"]*"/, `<meta name="description" content="${d.meta}"`);

  // 3) Product JSON-LD : description enrichie (anchor = @type:"Product" dans le bloc)
  const blocks = [...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
  const prodBlock = blocks.find(m => m[1].includes('"@type":"Product"'));
  if (!prodBlock) throw new Error(`Product JSON-LD non trouvé: ${d.file}`);
  const obj = JSON.parse(prodBlock[1]);
  obj.description = d.productDescription;
  const newProduct = JSON.stringify(obj);
  const faqLd = JSON.stringify(d.faq);
  html = html.replace(prodBlock[0],
    `<script type="application/ld+json">${newProduct}</script>\n  <script type="application/ld+json">${faqLd}</script>`);

  // 4) Onglet "Beschreibung" : remplir le product-description VIDE de l'onglet #description
  const tabRe = /(<div class="tab-pane fade in" id="description" role="tabpanel">[\s\S]*?<div class="product-description">)(\s*?)(<\/div>)/;
  const tb = html.match(tabRe);
  if (!tb) throw new Error(`Onglet description introuvable: ${d.file}`);
  html = html.replace(tabRe, `$1\n${d.desc}\n$3`);

  // 5) Section FAQ après le script cart.js
  html = html.replace(/(<script src="\.\.\/\.\.\/assets\/js\/cart\.js"><\/script>)/, `$1\n\n${d.section}`);

  // Marqueur d'idempotence dans le <head>
  html = html.replace('<!-- seo-enriched-v1 -->', `<!-- seo-enriched-v1 -->\n  ${MARK}`);

  writeFileSync(d.file, html, 'utf8');
  changed++;
  console.log(`OK enrichi: ${d.file}`);
}
